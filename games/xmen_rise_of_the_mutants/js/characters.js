  // Ratings out of 10 for the character select bars.
  XM.charRatings = function (c) {
    const s = c.stats;
    const r = (v, lo, hi) => Math.round(XM.U.clamp(((v - lo) / (hi - lo)) * 9 + 1, 1, 10));
    return [
      ["Health", r(s.hp, 80, 180)],
      ["Attack", r(s.atk, 8, 16)],
      ["Speed", r(s.spd, 215, 290)],
      ["Jump", c.move === "levitate" ? 7 : r(s.jump + (c.dj ? 0.8 : 0), 3.1, 4.6)],
      ["Special", r(s.sp, 0.95, 1.4)],
      ["X-Energy", r(s.energy, 85, 150)],
      ["Ultimate", r(s.ult, 1.1, 1.5)],
      ["Defense", r(s.def, 0.02, 0.24)],
    ];
  };
